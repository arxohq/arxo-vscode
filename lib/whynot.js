'use strict';
// "Why not" §185: output of `lawc why-not <directory> --json` → panel nodes.
//
// The sections, their titles and caveats are taken verbatim from the command
// itself (law-cli/src/explain.rs, `render_why_not`). A wording of our own
// would mean a second semantics of the explanation — and §185 is precisely
// about what may NOT be asserted: "undetermined" is not called a blocker,
// because the absence of support is not falsity. Empty sections are not
// shown for the same reason the command doesn't print them: a section with
// no rows reads as an unstated claim.

// Rule name at the end of a StableId §14 (`urn:…#AdmitFiled`). Navigation is
// offered only where the subject has this shape: for "missing judgment" it
// is the query's id, for source blockers it is the edition's id, and there
// is nothing to open by them. A rule generated by an expansion §279.1.4
// carries slashes: `X/elements`, `X/exemption/Voluntary/excludes` — the
// anchor leads to the instance (bridged in extension.js).
const RULE_SUBJECT = /#([A-Za-z_][A-Za-z0-9_]*(?:\/[A-Za-z0-9_]+)*)$/;

const node = (label, kind, extra = {}) => ({
  label,
  description: '',
  status: '',
  id: '',
  kind,
  children: [],
  anchor: null,
  ...extra,
});

function leaf(item, kind) {
  const subject = item.subject ?? '';
  const match = RULE_SUBJECT.exec(subject);
  return node(subject ? (match ? match[1] : subject) : (item.kind ?? '?'), kind, {
    description: item.detail ?? item.why ?? '',
    // Kind §185 — next to the name, but only where the name isn't it itself.
    status: subject ? (item.kind ?? '') : '',
    id: subject,
    children: [],
    anchor: match ? { kind: 'rule', name: match[1] } : null,
  });
}

const section = (title, items, kind) =>
  node(title, kind, { children: items.map((item) => leaf(item, kind)) });

/** Roots of the "why not" panel tree. */
function whyNotTree(payload) {
  if (!payload || payload.ok === false) {
    return [node('why-not did not run', 'error', {
      description: payload?.error ?? 'empty compiler response',
    })];
  }

  const roots = [node(`result status: ${payload.status ?? '?'}`, 'status')];

  const blockers = payload.blockers ?? [];
  roots.push(blockers.length
    ? section(`blockers (${blockers.length})`, blockers, 'blocker')
    : node('no blockers confirmed by the document', 'none'));

  const observations = payload.observations ?? [];
  if (observations.length) {
    roots.push(section(
      `undetermined (${observations.length}) — the condition is NOT refuted, there simply is no conclusion`,
      observations, 'observation'));
  }

  const undeterminable = payload.undeterminable ?? [];
  if (undeterminable.length) {
    roots.push(section('kinds §185 that CANNOT be determined from the document (this does not mean "there are none")',
      undeterminable, 'undeterminable'));
  }

  const inapplicable = payload.notApplicableAtEvaluation ?? [];
  if (inapplicable.length) {
    roots.push(section('kinds §185 that cannot occur at this stage by construction',
      inapplicable, 'inapplicable'));
  }

  return roots;
}

module.exports = { whyNotTree, RULE_SUBJECT };
